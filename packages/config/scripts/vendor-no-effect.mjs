// Writes oxlint/no-effect.mjs: one file that holds the plugin and its only
// import (globals). A dependency would make every app install ESLint, because
// the plugin names it as a peer. Run after a plugin version change:
//   pnpm --filter @vvedantb/config vendor:no-effect
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(pkgDir, "package.json"));
const name = "eslint-plugin-react-you-might-not-need-an-effect";
const entry = require.resolve(name);
const pluginDir = join(dirname(entry), "..");
const { version } = JSON.parse(readFileSync(join(pluginDir, "package.json"), "utf8"));

const banner = [
  `// GENERATED by scripts/vendor-no-effect.mjs. Do not edit.`,
  `// ${name} ${version}, MIT License, Copyright (c) 2025 Nick van Dyke.`,
  `// It includes globals, MIT License, Copyright (c) Sindre Sorhus.`,
  `// The full licence texts are in oxlint/NO-EFFECT-LICENSES.txt.`,
].join("\n");

await build({
  entryPoints: [entry],
  outfile: join(pkgDir, "oxlint", "no-effect.mjs"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  legalComments: "none",
  banner: { js: banner },
});
